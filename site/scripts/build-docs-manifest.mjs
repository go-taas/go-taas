#!/usr/bin/env node
// Builds site/docs/manifest.json — the index the documentation browser
// (site/docs.html) reads to render its sidebar, search and table of contents.
//
// Usage:
//   node site/scripts/build-docs-manifest.mjs           # (re)write the manifest
//   node site/scripts/build-docs-manifest.mjs --check    # fail if it is stale
//
// The manifest holds metadata only (title, heading outline, document scope);
// document bodies are fetched on demand from site/docs/**. It is committed so
// that a plain static server can preview the documentation without running Node,
// and it is regenerated by the GitHub Pages workflow before every deploy.

import { readdir, readFile, stat, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const SITE = resolve(HERE, "..");
const DOCS = join(SITE, "docs");
const MANIFEST = join(DOCS, "manifest.json");
const CHECK = process.argv.includes("--check");

/** Sections shown in the sidebar, in order, with their localized labels. */
const SECTIONS = [
  { id: "getting-started", title: { en: "Getting started", "zh-CN": "快速开始" } },
  { id: "design", title: { en: "Design documents", "zh-CN": "设计文档" } },
  { id: "architecture", title: { en: "Architecture documents", "zh-CN": "架构文档" } },
];

/** Matches the metadata table that every document carries under its title. */
const META_HEADERS = new Set(["attribute|content", "属性|内容"]);

/**
 * Slugifies a heading the way GitHub does, so the anchors the browser renders
 * match the ones GitHub generates for the same source.
 */
function slugify(text, seen) {
  const base =
    text
      .replace(/<[^>]*>/g, "")
      .replace(/`/g, "")
      .trim()
      .toLowerCase()
      // Keep unicode letters, numbers, marks and connector punctuation; drop
      // everything else that GitHub drops from an anchor.
      .replace(/[^\p{L}\p{N}\p{M}\p{Pc}\- ]/gu, "")
      .replace(/ +/g, "-");
  const count = seen.get(base) ?? 0;
  seen.set(base, count + 1);
  return count === 0 ? base : `${base}-${count}`;
}

/** Splits one markdown table row into its cells. */
function cells(line) {
  return line
    .replace(/^\|/, "")
    .replace(/\|$/, "")
    .split("|")
    .map((cell) => cell.trim());
}

/**
 * Parses one markdown document: the H1 title, the metadata table, and the
 * heading outline used for the in-page table of contents.
 */
function parseDocument(source) {
  const lines = source.split("\n");
  const headings = [];
  const seen = new Map();
  let title = "";
  const meta = {};

  for (let i = 0; i < lines.length; i += 1) {
    const line = lines[i];
    const heading = /^(#{1,3})\s+(.+?)\s*$/.exec(line);
    if (heading) {
      const level = heading[1].length;
      // Inline code and emphasis are common in these headings; strip them so
      // the sidebar and table of contents read as plain text.
      const text = heading[2].replace(/`([^`]*)`/g, "$1").replace(/\*\*/g, "");
      if (level === 1) {
        if (!title) title = text;
        continue;
      }
      headings.push({ level, text, id: slugify(heading[2], seen) });
      continue;
    }
    // The metadata table is the first table in the document.
    if (Object.keys(meta).length === 0 && line.startsWith("|")) {
      const header = cells(line).join("|").toLowerCase();
      if (!META_HEADERS.has(header) || lines[i + 1]?.trim() !== "| --- | --- |") continue;
      i += 2;
      for (; i < lines.length && lines[i].startsWith("|"); i += 1) {
        const [key, ...rest] = cells(lines[i]);
        if (key) meta[key] = rest.join("|").trim();
      }
      i -= 1;
    }
  }
  return { title, meta, headings };
}

/** Reads the handful of metadata fields the browser surfaces. */
function summary(meta, lang) {
  const pick = (...keys) => {
    for (const key of keys) {
      if (meta[key]) return meta[key];
    }
    return "";
  };
  const scope = pick("Document scope", "文档范围").replace(/<br\s*\/?>/gi, " ");
  return {
    featurePoint: pick("Feature point", "功能点").replace(/<br\s*\/?>/gi, " "),
    scope,
    status: pick("Status", "状态"),
    owner: pick("Owning module", "所属模块"),
  };
}

/** Lists the markdown files of one section, keyed by feature (without suffix). */
async function sectionDocs(id) {
  let entries;
  try {
    entries = await readdir(join(DOCS, id), { withFileTypes: true });
  } catch {
    return [];
  }
  const byFeature = new Map();
  for (const entry of entries) {
    if (!entry.isFile() || !entry.name.endsWith(".md")) continue;
    const isZh = entry.name.endsWith(".zh-cn.md");
    const key = entry.name.replace(/\.zh-cn\.md$/, "").replace(/\.md$/, "");
    const lang = isZh ? "zh-CN" : "en";
    const rel = relative(DOCS, join(DOCS, id, entry.name)).split(sep).join("/");
    const source = await readFile(join(DOCS, id, entry.name), "utf8");
    const { title, meta, headings } = parseDocument(source);
    const doc = { path: rel, lang, title, headings, ...summary(meta, lang) };
    const entryFor = byFeature.get(key) ?? {};
    entryFor[lang] = doc;
    byFeature.set(key, entryFor);
  }
  // The platform architecture document leads its section; everything else
  // follows in alphabetical order.
  const LEAD = "architecture";
  return [...byFeature.entries()]
    .map(([key, variants]) => ({ key, ...variants }))
    .sort((a, b) => {
      if (a.key === LEAD) return -1;
      if (b.key === LEAD) return 1;
      const left = (a.en ?? a["zh-CN"]).title.toLowerCase();
      const right = (b.en ?? b["zh-CN"]).title.toLowerCase();
      return left.localeCompare(right);
    });
}

/** Summarizes the generated OpenAPI specs, when `make pbgen` has produced them. */
async function apiSpecs() {
  const root = join(DOCS, "api", "taas");
  let services;
  try {
    services = await readdir(root, { withFileTypes: true });
  } catch {
    return [];
  }
  const specs = [];
  for (const service of services.filter((entry) => entry.isDirectory()).sort((a, b) => a.name.localeCompare(b.name))) {
    const file = join(root, service.name, "v1", `${service.name}.swagger.json`);
    try {
      const spec = JSON.parse(await readFile(file, "utf8"));
      const operations = Object.entries(spec.paths ?? {})
        .flatMap(([path, methods]) =>
          Object.entries(methods).map(([method, operation]) => ({
            method: method.toUpperCase(),
            path,
            summary: operation.summary ?? operation.operationId ?? "",
          })),
        )
        .sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));
      // A proto file without RPCs (shared messages only) is not an API entry.
      if (operations.length === 0) continue;
      specs.push({
        service: service.name,
        title: service.name.charAt(0).toUpperCase() + service.name.slice(1),
        proto: `taas/${service.name}/v1/${service.name}.proto`,
        operations,
      });
    } catch {
      // A spec that has not been generated is simply not listed.
    }
  }
  return specs;
}

async function build() {
  const sections = [];
  for (const section of SECTIONS) {
    const docs = await sectionDocs(section.id);
    if (docs.length > 0) sections.push({ ...section, docs });
  }
  const api = await apiSpecs();
  if (api.length > 0) {
    sections.push({
      id: "api",
      title: { en: "API reference", "zh-CN": "API 参考" },
      specs: api,
    });
  }
  return {
    generated: new Date().toISOString().replace(/\.\d{3}Z$/, "Z"),
    sections,
  };
}

const manifest = `${JSON.stringify(await build())}\n`;
const docs = manifest.match(/"path":/g)?.length ?? 0;

if (CHECK) {
  let current = "";
  try {
    current = await readFile(MANIFEST, "utf8");
  } catch {
    process.stderr.write("site/docs/manifest.json is missing. Run: node site/scripts/build-docs-manifest.mjs\n");
    process.exit(1);
  }
  // The timestamp changes on every run, so it is not part of the comparison.
  const strip = (value) => value.replace(/"generated":\s*"[^"]*",?/, "");
  if (strip(current) !== strip(manifest)) {
    process.stderr.write("site/docs/manifest.json is stale. Run: node site/scripts/build-docs-manifest.mjs\n");
    process.exit(1);
  }
  process.stdout.write("site/docs/manifest.json is up to date\n");
} else {
  await writeFile(MANIFEST, manifest);
  const size = (await stat(MANIFEST)).size;
  const counts = (await build()).sections
    .map((section) => `${section.id}: ${section.docs?.length ?? section.specs?.length ?? 0}`)
    .join(", ");
  process.stdout.write(`wrote site/docs/manifest.json (${docs} documents, ${(size / 1024).toFixed(0)} KiB — ${counts})\n`);
}
